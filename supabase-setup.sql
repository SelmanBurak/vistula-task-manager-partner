-- Run this in the Supabase SQL Editor for a dedicated demonstration project.
-- This intentionally allows unauthenticated public CRUD access for the assignment.
-- Keep only test data in this table and never use a service-role key in the frontend.

create table if not exists public.tasks (
    id bigint generated by default as identity primary key,
    title text not null,
    description text not null default '',
    completed boolean not null default false
);

alter table public.tasks enable row level security;

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on table public.tasks to anon, authenticated;
grant usage, select on sequence public.tasks_id_seq to anon, authenticated;

drop policy if exists "Public can read tasks" on public.tasks;
create policy "Public can read tasks"
    on public.tasks for select
    to anon, authenticated
    using (true);

drop policy if exists "Public can insert tasks" on public.tasks;
create policy "Public can insert tasks"
    on public.tasks for insert
    to anon, authenticated
    with check (true);

drop policy if exists "Public can update tasks" on public.tasks;
create policy "Public can update tasks"
    on public.tasks for update
    to anon, authenticated
    using (true)
    with check (true);

drop policy if exists "Public can delete tasks" on public.tasks;
create policy "Public can delete tasks"
    on public.tasks for delete
    to anon, authenticated
    using (true);

